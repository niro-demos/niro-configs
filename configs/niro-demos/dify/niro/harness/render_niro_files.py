#!/usr/bin/env python3
"""Render niro/credentials.yaml and niro/fixtures.yaml from seed_dify.py's
JSON output.

Usage: seed_dify.py's stdout JSON is piped in on stdin:
    docker compose exec -T api python3 /tmp/niro_seed.py | \
        python3 niro/harness/render_niro_files.py <niro_config_dir>

Kept separate from seed_dify.py because seed_dify.py runs inside the api
container (only stdlib + app deps available there); this renderer runs on
the host, where PyYAML is available, and owns the actual niro/*.yaml file
format/schema decisions.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import yaml


HEADER = (
    "# yaml-language-server: $schema=https://niro.apxlabs.ai/schema/v1/{schema}.json\n"
    "#\n"
    "# GENERATED by niro/harness/seed.sh -> render_niro_files.py. Do not edit by\n"
    "# hand; re-run niro/harness/seed.sh (or reset.sh) to regenerate.\n"
    "# Source of truth for how this is produced: niro/harness/seed_dify.py.\n"
)


def dump(obj: dict) -> str:
    return yaml.safe_dump(obj, sort_keys=False, allow_unicode=True, width=100)


