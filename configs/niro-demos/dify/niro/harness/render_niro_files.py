def _without_secret(value: dict) -> dict:
    """Fixtures announce reference points, not auth material -- api_key lives
    in credentials.yaml (APP_A_SERVICE_API_KEY / APP_B_SERVICE_API_KEY /
    DATASET_A_API_KEY) only."""
    return {k: v for k, v in value.items() if k != "api_key"}


def build_fixtures(data: dict) -> dict:
    fixtures = [
        {
            "name": "tenant_org_a",
            "description": "Seeded tenant 'Niro Org A'. Owns app_a and dataset_a. Members: OWNER_A, "
            "ADMIN_A, EDITOR_A, NORMAL_A, DSOP_A credentials.",
            "value": data["tenants"]["org_a"],
        },
        {
            "name": "tenant_org_b",
            "description": "Seeded tenant 'Niro Org B', fully independent from Org A (no shared "
            "members). Owns app_b. Members: OWNER_B, NORMAL_B credentials.",
            "value": data["tenants"]["org_b"],
        },
        {
            "name": "app_a",
            "description": "Seeded chat app owned by Org A. id/mode useful for /console/api/apps/<id>/* "
            "and /v1/* (with APP_A_SERVICE_API_KEY) endpoint construction. api_key lives in "
            "credentials.yaml, not here.",
            "value": _without_secret(data["apps"]["app_a"]),
        },
        {
            "name": "app_b",
            "description": "Seeded chat app owned by Org B, the cross-tenant counterpart to app_a. "
            "api_key lives in credentials.yaml, not here.",
            "value": _without_secret(data["apps"]["app_b"]),
        },
        {
            "name": "dataset_a",
            "description": "Seeded empty dataset owned by Org A. Org B intentionally has no dataset. "
            "See DATASET_A_API_KEY in credentials.yaml for why this key is NOT scoped to only this "
            "dataset. api_key lives in credentials.yaml, not here.",
            "value": _without_secret(data["datasets"]["dataset_a"]),
        },
    ]
    return {"fixtures": fixtures}


def main() -> None:
    if len(sys.argv) != 2:
        print("usage: render_niro_files.py <niro_config_dir>", file=sys.stderr)
        raise SystemExit(2)
    niro_dir = Path(sys.argv[1])

    raw = sys.stdin.read()
    try:
        data = json.loads(raw)
    except json.JSONDecodeError as exc:
        print("render_niro_files.py: seed script did not print valid JSON on stdout", file=sys.stderr)
        print(raw, file=sys.stderr)
        raise SystemExit(1) from exc

    creds_path = niro_dir / "credentials.yaml"
    fixtures_path = niro_dir / "fixtures.yaml"

    creds_path.write_text(HEADER.format(schema="credentials") + "\n" + dump(build_credentials(data)))
    fixtures_path.write_text(HEADER.format(schema="fixtures") + "\n" + dump(build_fixtures(data)))

    print(f"wrote {creds_path}")
    print(f"wrote {fixtures_path}")


if __name__ == "__main__":
    main()
